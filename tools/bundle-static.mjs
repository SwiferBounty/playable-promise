// Bundles public/ into worker/static-files.js (the Worker serves these itself; no asset upload step).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.json': 'application/json', '.ico': 'image/x-icon' };
const files = {};
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (TYPES[extname(p)]) files['/' + relative('public', p).split('\\').join('/')] = [TYPES[extname(p)], readFileSync(p).toString('base64')];
  }
})('public');
writeFileSync('worker/static-files.js', `// Generated by tools/bundle-static.mjs. Do not edit.\nexport default ${JSON.stringify(files)};\n`);
console.log(`bundled ${Object.keys(files).length} files`);
